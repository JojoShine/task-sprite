import {copyFileSync, mkdirSync, readFileSync, chmodSync, appendFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {spawnSync} from 'node:child_process';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
if (process.platform !== 'darwin' || process.arch !== 'arm64') throw new Error('The pinned agent requires an Apple Silicon macOS runner.');
const base = path.join(root, 'release-bootstrap/macos-aarch64');
const agent = path.join(base, 'task-sprite-credential-agent');
const metadata = JSON.parse(readFileSync(path.join(base, 'metadata.json'), 'utf8'));
if (createHash('sha256').update(readFileSync(agent)).digest('hex') !== metadata.sha256) throw new Error('Pinned credential agent checksum mismatch.');
const check = spawnSync('/usr/bin/codesign', ['--verify', '--strict', '-R', `=cdhash H"${metadata.cdhash}"`, agent], {encoding: 'utf8'});
if (check.status !== 0) throw new Error('Pinned credential agent signature mismatch.');
const bin = path.join(root, 'src-tauri/bin');
mkdirSync(bin, {recursive: true});
copyFileSync(agent, path.join(bin, 'task-sprite-credential-agent'));
chmodSync(path.join(bin, 'task-sprite-credential-agent'), 0o755);
if (process.env.GITHUB_ENV) appendFileSync(process.env.GITHUB_ENV, `TASK_SPRITE_AGENT_CDHASH=${metadata.cdhash}\nAPPLE_SIGNING_IDENTITY=-\n`);
console.log('Verified original credential agent. CI candidate uses ad-hoc app signing; final signing remains local.');
